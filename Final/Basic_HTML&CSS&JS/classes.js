// use PascalCase for classes
class HillBilly{
  constructor(name, job, iq){
    //this.name = our class field/property
    this.name = name;
    this.job = job;
    this.iq = iq;
  }
}

let hillBillyOne = new HillBilly("Billy Bob Joe", "Welder", -5);
console.log(hillBillyOne.name);
console.log(hillBillyOne.job);
console.log(hillBillyOne.iq);


